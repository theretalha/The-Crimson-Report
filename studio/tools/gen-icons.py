#!/usr/bin/env python3
"""Turn Lucide SVG icons (ISC licence) into src/pro/iconData.ts so the video can animate each stroke.
Usage: python3 tools/gen-icons.py cpu landmark server ...   (names as in node_modules/lucide-static/icons)"""
import json, re, sys, xml.etree.ElementTree as ET
from pathlib import Path
D = Path("node_modules/lucide-static/icons")
names = sys.argv[1:]
out = {}
for n in names:
    raw = re.sub(r"<!--.*?-->", "", (D / f"{n}.svg").read_text(), flags=re.S)
    root = ET.fromstring(raw)
    els = []
    for e in root:
        tag = e.tag.split("}")[-1]
        els.append({"t": tag, "a": dict(e.attrib)})
    out[n] = els
Path("src/pro/iconData.ts").write_text(
    "// generated by tools/gen-icons.py from lucide-static (ISC licence)\n"
    "export type IEl = {t: string; a: Record<string, string>};\n"
    "export const ICONS: Record<string, IEl[]> = " + json.dumps(out) + ";\n")
print(len(out), "icons ->", "src/pro/iconData.ts")
